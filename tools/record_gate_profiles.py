"""Writes tests/record_reference.hpp from the song corpus's features_ref.json: for each group of
records and each separated stem a preset can stand in for, the quartiles of the features
tests/record_features.hpp measures. Only numbers leave the corpus; no audio is copied.

    python3 -I tools/record_gate_profiles.py /path/to/song-corpus/features_ref.json > tests/record_reference.hpp
"""
import json
import statistics
import sys

GROUPS = ['GBV_lofi', 'OTC']
STEMS = ['piano', 'other']
FEATURES = ['centroid_hz', 'rolloff85_hz', 'hf_share_db', 'crest100_db', 'corr', 'wobble_cents']


def quartiles(values):
    q = statistics.quantiles(values, n=4, method='inclusive')
    return q[0], statistics.median(values), q[2]


def main():
    data = json.load(open(sys.argv[1]))
    out = ['// Generated by tools/record_gate_profiles.py from the song corpus\'s features_ref.json: htdemucs_6s',
           '// stems of 45 s excerpts of the user\'s own records, measured by its scripts/features.py. Numbers only.',
           '#pragma once', '', '#include <array>', '', 'namespace record {', '',
           'struct Stat { double q25, median, q75; };',
           'struct Reference {',
           '  const char* group;',
           '  const char* stem;',
           '  int tracks;',
           '  Stat ' + ', '.join(FEATURES) + ';',
           '};', '',
           'inline constexpr std::array kReferences{']
    for group in GROUPS:
        for stem in STEMS:
            rows = [v[stem] for k, v in sorted(data.items()) if k.startswith(group + '_') and 'centroid_hz' in v.get(stem, {})]
            stats = []
            for f in FEATURES:
                values = [r[f] for r in rows if r.get(f) is not None]
                stats.append('{%.4g, %.4g, %.4g}' % quartiles(values))
            out.append('    Reference{"%s", "%s", %d,\n              %s},' % (group, stem, len(rows), ', '.join(stats)))
    out += ['};', '', '}  // namespace record', '']
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
